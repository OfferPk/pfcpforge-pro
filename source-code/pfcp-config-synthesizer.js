/**
 * PFCPForge Pro - Multi-Platform Configuration Synthesizer
 * Generates verified production syntax for:
 * 1. Open5GS UPF (upf.yaml) & SMF (smf.yaml)
 * 2. Free5GC UPF Configuration (upfcfg.yaml)
 * 3. Cisco cUPF / ASR 5500 N4 Service
 * 4. Juniper Junos Security Filter & CoPP for UDP 8805
 * 5. Prometheus N4 / PFCP Exporter Alerting Rules
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.PFCPConfigSynthesizer = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  function generateOpen5GS(cfg) {
    const smfIp = cfg.smfIp || '10.200.1.10';
    const upfIp = cfg.upfIp || '10.200.1.20';
    const gnbIp = cfg.gnbIp || '198.51.100.10';
    const dnn = cfg.dnn || 'internet';
    const poolSubnet = cfg.poolSubnet || '10.45.0.0/16';
    const hbInterval = parseInt(cfg.heartbeatIntervalSec, 10) || 10;

    return `# ==============================================================================
# Open5GS 5G Core User Plane Function (upf.yaml)
# Generated by PFCPForge Pro v1.0.0 (3GPP TS 29.244 / TS 23.501)
# ==============================================================================

logger:
  file: /var/log/open5gs/upf.log
  level: info

upf:
  pfcp:
    dev: eth0
    server:
      - address: ${upfIp}
        port: 8805
    client:
      smf:
        - address: ${smfIp}
          port: 8805
    heartbeat:
      interval: ${hbInterval}
      max_retries: 3

  gtpu:
    dev: eth1
    server:
      - address: ${upfIp}
    advertise:
      - address: ${upfIp}

  subnet:
    - addr: ${poolSubnet}
      dnn: ${dnn}
      dev: ogstun

# Buffer limits for idle UEs
buffering:
  max_packets: ${cfg.maxBufferPackets || 50}
  timeout: ${cfg.bufferTimeoutSec || 5}
`;
  }

  function generateFree5GC(cfg) {
    const smfIp = cfg.smfIp || '10.200.1.10';
    const upfIp = cfg.upfIp || '10.200.1.20';
    const dnn = cfg.dnn || 'internet';

    return `# ==============================================================================
# Free5GC 5G Standalone UPF Configuration (upfcfg.yaml)
# Generated by PFCPForge Pro v1.0.0 (3GPP Release 16)
# ==============================================================================

version: 1.0.3
description: Free5GC UPF Configuration

logger:
  UPF:
    ReportCaller: false
    debugLevel: info

pfcp:
  addr: ${upfIp}
  nodeID: ${upfIp}
  retransmission:
    timer: 1000ms
    max_retries: 3

gtpu:
  forwarder: gtp5g
  ifList:
    - addr: ${upfIp}
      type: N3

dnnList:
  - dnn: ${dnn}
    cidr: ${cfg.poolSubnet || '10.45.0.0/16'}

# Zero-Trust PDR/FAR Buffering Protection
bufferProfile:
  enabled: ${cfg.bufferingProtectionEnabled ? 'true' : 'false'}
  packetCap: ${cfg.maxBufferPackets || 50}
  timeoutSec: ${cfg.bufferTimeoutSec || 5}
`;
  }

  function generateCisco(cfg) {
    const smfIp = cfg.smfIp || '10.200.1.10';
    const upfIp = cfg.upfIp || '10.200.1.20';

    let out = [];
    out.push('! ==============================================================================');
    out.push('! Cisco cUPF / ASR 5500 N4 Service Configuration');
    out.push('! Generated by PFCPForge Pro v1.0.0 (3GPP TS 29.244 CUPS)');
    out.push('! ==============================================================================');
    out.push('!');
    out.push('context 5g-user-plane');
    out.push('  user-plane-service UPF-SERVICE');
    out.push(`    bind ipv4-address ${upfIp}`);
    out.push('    gtpu-service N3-GTPU');
    out.push('    fast-path-forwarding enabled');
    if (cfg.bufferingProtectionEnabled) {
      out.push(`    downlink-buffering max-packets-per-bearer ${cfg.maxBufferPackets || 50}`);
      out.push(`    downlink-buffering hold-timer ${cfg.bufferTimeoutSec || 5}`);
    }
    out.push('  exit');
    out.push('!');
    out.push('  pfcp-service N4-PFCP');
    out.push(`    bind ipv4-address ${upfIp} port 8805`);
    out.push(`    heartbeat-timer ${cfg.heartbeatIntervalSec || 10}`);
    out.push('    heartbeat-max-retries 3');
    out.push(`    associate peer-smf ${smfIp}`);
    if (cfg.seidIsolationEnabled) {
      out.push('    seid-allocation-mode cryptographic-random-64bit');
    }
    out.push('  exit');
    out.push('exit');
    out.push('!');

    if (cfg.coppEnabled) {
      out.push('! Control Plane Policing for UDP Port 8805');
      out.push('ip access-list ACL-N4-PFCP');
      out.push(` permit udp host ${smfIp} host ${upfIp} eq 8805`);
      out.push(' deny udp any any eq 8805');
      out.push('!');
      out.push('policy-map POLICY-COPP-PFCP');
      out.push(' class ACL-N4-PFCP');
      out.push('  police rate 50000 pps conform-action transmit exceed-action drop');
      out.push('!');
    }

    return out.join('\n');
  }

  function generateJunos(cfg) {
    const upfIp = cfg.upfIp || '10.200.1.20';
    const smfIp = cfg.smfIp || '10.200.1.10';

    let out = [];
    out.push('# ==============================================================================');
    out.push('# Juniper Junos Security Filter & CoPP for 5G N4 (UDP 8805)');
    out.push('# Generated by PFCPForge Pro v1.0.0');
    out.push('# ==============================================================================');
    out.push('');
    out.push(`set firewall family inet filter FILTER-5G-N4 term ALLOW-AUTHORIZED-SMF from source-address ${smfIp}`);
    out.push(`set firewall family inet filter FILTER-5G-N4 term ALLOW-AUTHORIZED-SMF from destination-address ${upfIp}`);
    out.push('set firewall family inet filter FILTER-5G-N4 term ALLOW-AUTHORIZED-SMF from protocol udp');
    out.push('set firewall family inet filter FILTER-5G-N4 term ALLOW-AUTHORIZED-SMF from destination-port 8805');
    if (cfg.coppEnabled) {
      out.push('set firewall family inet filter FILTER-5G-N4 term ALLOW-AUTHORIZED-SMF then policer POLICER-PFCP-50K');
      out.push('set firewall policer POLICER-PFCP-50K if-exceeding bandwidth-limit 200m burst-size-limit 256k');
      out.push('set firewall policer POLICER-PFCP-50K then discard');
    }
    out.push('set firewall family inet filter FILTER-5G-N4 term ALLOW-AUTHORIZED-SMF then accept');
    out.push('');
    out.push('set firewall family inet filter FILTER-5G-N4 term DROP-UNAUTHORIZED-UDP8805 from protocol udp');
    out.push('set firewall family inet filter FILTER-5G-N4 term DROP-UNAUTHORIZED-UDP8805 from destination-port 8805');
    out.push('set firewall family inet filter FILTER-5G-N4 term DROP-UNAUTHORIZED-UDP8805 then log');
    out.push('set firewall family inet filter FILTER-5G-N4 term DROP-UNAUTHORIZED-UDP8805 then discard');
    out.push('');

    return out.join('\n');
  }

  function generatePrometheus(cfg) {
    return `# ==============================================================================
# Prometheus 5G N4 / PFCP Alerting Rules (3GPP TS 29.244 Telemetry)
# Generated by PFCPForge Pro v1.0.0
# ==============================================================================

groups:
  - name: 5g_n4_pfcp_alerts
    rules:
      - alert: PFCPHeartbeatTimeout
        expr: pfcp_association_status{state!="ACTIVE"} == 1
        for: 15s
        labels:
          severity: critical
          tier: 5g-packet-core
        annotations:
          summary: "N4 Association Severed: SMF {{ $labels.smf_ip }} <-> UPF {{ $labels.upf_ip }}"
          description: "PFCP Heartbeat failure. Control/User plane separation link lost. In-flight PDU sessions may be blackholed."

      - alert: PFCPDownlinkBufferOverflow
        expr: rate(upf_dl_buffer_drops_total[1m]) > 50
        for: 30s
        labels:
          severity: critical
          tier: upf-dataplane
        annotations:
          summary: "UPF Downlink Data Buffering Overflow on {{ $labels.instance }}"
          description: "High volume of buffered downlink packets dropped during UE paging. Risk of UPF kernel OOM crash."

      - alert: PFCPSessionDropRateHigh
        expr: rate(pfcp_session_errors_total[2m]) > 20
        for: 1m
        labels:
          severity: warning
          tier: smf-signaling
        annotations:
          summary: "Elevated PFCP Session Establishment Rejection Rate"
          description: "SMF reports high rejection count for Session Establishment/Modification Requests. Check rule precedence or resource quota."
`;
  }

  return {
    generateOpen5GS,
    generateFree5GC,
    generateCisco,
    generateJunos,
    generatePrometheus
  };
}));
